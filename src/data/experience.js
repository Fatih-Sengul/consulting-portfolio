// Helper function to calculate total years of experience
export const calculateTotalYears = () => {
  const now = new Date();
  let totalMonths = 0;

  experiences.forEach((exp) => {
    const start = new Date(exp.startDate);
    const end = exp.endDate ? new Date(exp.endDate) : now;
    const months =
      (end.getFullYear() - start.getFullYear()) * 12 +
      (end.getMonth() - start.getMonth());
    totalMonths += months;
  });

  return (totalMonths / 12).toFixed(1);
};

// Helper function to calculate experience by category
export const calculateCategoryYears = (categoryName) => {
  const now = new Date();
  let totalMonths = 0;

  experiences
    .filter((exp) => exp.category.includes(categoryName))
    .forEach((exp) => {
      const start = new Date(exp.startDate);
      const end = exp.endDate ? new Date(exp.endDate) : now;
      const months =
        (end.getFullYear() - start.getFullYear()) * 12 +
        (end.getMonth() - start.getMonth());
      totalMonths += months;
    });

  return (totalMonths / 12).toFixed(1);
};

// Helper function to count ambassador programs
export const countAmbassadorPrograms = () => {
  return experiences.filter((exp) =>
    exp.category.includes('Ambassador / Community')
  ).length;
};

// Helper function to get unique categories
export const getUniqueCategories = () => {
  const categories = new Set();
  experiences.forEach((exp) => {
    exp.category.forEach((cat) => categories.add(cat));
  });
  return Array.from(categories);
};

// Helper function to get unique location types
export const getUniqueLocationTypes = () => {
  const types = new Set();
  experiences.forEach((exp) => {
    types.add(exp.locationType);
  });
  return Array.from(types);
};
